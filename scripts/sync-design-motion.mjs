// Motion outputs of the Design System sync (scripts/sync-design-tokens.mjs):
// the box-open loader CSS and SVG markup (design-kit/motion/box-open/) and the
// theme reveal CSS (design-kit/motion/theme-reveal/). Pure string transforms so
// tests/unit/design-kit-sync.test.ts can compare the committed files.

export const triplet = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(" ");

/** The app's three dark scopes (docs/DESIGN.md §9.1): explicit dark, dark bands and the OS fallback. */
function darkRules(rules) {
  const scoped = (prefix) => rules.map(([selector, body]) => `${prefix(selector)}{${body}}`).join("\n");
  return `${scoped((s) => `:root[data-color-mode="dark"] ${s},.yy-dark-band ${s}`)}
@media (prefers-color-scheme:dark){
${scoped((s) => `:root:not([data-color-mode]) ${s}`)}
}`;
}

const ground = (loader) => `--sw-under:rgb(${triplet(loader.under)});--sw-spark:rgb(${triplet(loader.spark)});--sw-seam:rgb(${triplet(loader.seam)})`;

/**
 * The kit's box-open.css with its theme rules rewritten for this app: the
 * loader colours come from the synced `--sw-loader-*` triplets (palette.css),
 * `html.dark` becomes the app's dark scopes, and the one-shot `once` cycle
 * (the cold-start splash, which the app does not use) is dropped. The loop,
 * hover cycle, mono variant and reduced-motion rule are copied unchanged.
 */
export function generateBoxOpenCss(kitCss, tokens, version) {
  const kept = kitCss.trim().split("\n").filter((line) =>
    !line.startsWith("/*") && !line.startsWith(".sw-box.once") && !/#[\da-f]{3,8}\b|html\.dark/i.test(line));
  for (const marker of [".sw-box.loop .f-", ".sw-box.hov .f-", ".sw-box.mono{", "@keyframes sw-box-spark", "prefers-reduced-motion"]) {
    if (!kept.some((line) => line.includes(marker))) throw new Error(`box-open.css no longer has "${marker}"; update scripts/sync-design-motion.mjs`);
  }
  const { light, dark } = tokens.loader;
  return `/* Space Works Design System ${version} box-open loader (design-kit/motion/box-open/box-open.css), generated by
 * scripts/sync-design-tokens.mjs. Do not edit by hand. Colours: --sw-loader-* in palette.css (tokens.json "loader").
 * .lt is the full-colour artwork, .dk the reversed one; g-dark / g-light force a ground for the logo hover cycle. */
.sw-box{position:relative;--sw-under:rgb(var(--sw-loader-under));--sw-spark:rgb(var(--sw-loader-spark));--sw-seam:rgb(var(--sw-loader-seam))}
.sw-box .dk{display:none}
.sw-box .w{fill:var(--sw-under);opacity:0}
${kept.join("\n")}
.sw-box.g-dark{${ground(dark)}}
.sw-box.g-dark .lt{display:none}.sw-box.g-dark .dk{display:block}.sw-box.g-dark .w{fill:var(--sw-spark);fill-opacity:.14}
${darkRules([
    [".sw-box .lt", "display:none"],
    [".sw-box .dk", "display:block"],
    [".sw-box:not(.mono) .w", "fill:var(--sw-spark);fill-opacity:.14"],
    [".sw-box.g-light", ground(light)],
    [".sw-box.g-light .dk", "display:none"],
    [".sw-box.g-light .lt", "display:block"],
    [".sw-box.g-light .w", "fill:var(--sw-under);fill-opacity:1"],
  ])}
`;
}

/** tokens.json brand names -> the raw brand variables in app/styles/tokens.css. */
const BRAND_VARS = {
  "deep-ink": "ink", "maker-teal": "teal", "workshop-orange": "orange", citron: "citron",
  "sky-blue": "sky", "warm-yellow": "yellow", "warm-cream": "cream",
};

/**
 * The kit's box-open-markup.html (both artworks, `.lt` and `.dk`) as a TS
 * string. The logo masters' own fills are brand colours, so each hex becomes
 * its raw brand variable (`--sw-teal`, ...) and `fill` attributes become
 * inline `fill:` declarations that can read them. Components stay hex-free.
 */
export function generateBoxOpenMarkup(html, tokens, version) {
  const vars = new Map(Object.entries(tokens.brand).map(([name, hex]) => [hex.toUpperCase(), `var(--sw-${BRAND_VARS[name]})`]));
  const svg = html.trim()
    .replace(/#[\da-f]{6}\b/gi, (hex) => {
      const value = vars.get(hex.toUpperCase());
      if (!value) throw new Error(`box-open markup uses ${hex}, which is not a brand colour`);
      return value;
    })
    .replace(/ fill="([^"]+)" style="([^"]*)"/g, ' style="fill:$1;$2"')
    .replace(/ fill="(var\([^"]+\))"/g, ' style="fill:$1"');
  if (/#[\da-f]{3}/i.test(svg) || !svg.includes('<svg class="lt"') || !svg.includes('<svg class="dk"')) {
    throw new Error("box-open-markup.html changed shape; update scripts/sync-design-motion.mjs");
  }
  return `// Space Works Design System ${version} box-open artwork (design-kit/motion/box-open/box-open-markup.html),
// generated by scripts/sync-design-tokens.mjs. Do not edit by hand. Both artworks are present: .lt (full colour)
// and .dk (reversed); app/styles/box-open.css shows the one for the current colour mode.
export const BOX_OPEN_SVG =
  ${JSON.stringify(svg)};
`;
}

/** The kit's theme-reveal.css, unchanged (lib/themeTransition.ts drives its classes). */
export function generateThemeRevealCss(css, version) {
  return `/* Space Works Design System ${version} theme reveal (design-kit/motion/theme-reveal/theme-reveal.css),
 * copied by scripts/sync-design-tokens.mjs. Do not edit by hand; lib/themeTransition.ts adds the classes. */
${css.trim()}
`;
}

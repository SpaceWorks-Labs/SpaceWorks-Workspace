#!/usr/bin/env node
// Design System -> app sync. SpaceWorks-Design-System (git submodule at
// ./design-kit) is the source of truth for colour, chart, loader and motion
// tokens, the box-open loader, the theme reveal and font files; this script
// regenerates the committed outputs from it so builds and CI never need the submodule.
//
//   npm run tokens:sync                  # reads design-kit/
//   npm run tokens:sync -- --from <dir>  # reads another Design System checkout
//
// Outputs (deterministic, committed): app/styles/palette.css,
// app/styles/motion.css, app/styles/box-open.css, app/styles/theme-reveal.css,
// components/brand/boxOpenMarkup.ts, tests/fixtures/design-tokens.json,
// public/brand/fonts/** and public/brand/logo/*.svg.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { generateBoxOpenCss, generateBoxOpenMarkup, generateThemeRevealCss, triplet } from "./sync-design-motion.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Latest "### SpaceWorks x.y.z token sync" heading in the kit README. */
export function kitVersion(readme) {
  return readme.match(/^### SpaceWorks (\S+) token sync/m)?.[1] ?? "unknown";
}

/** Colour roles, the shadow colour, then the chart series and box-loader colours of one mode. */
function colourLines(tokens, mode, indent) {
  const lines = Object.entries(tokens[mode]).map(([name, hex]) => `${indent}--sw-color-${name}: ${triplet(hex)};`);
  lines.push(`${indent}--sw-shadow-color: ${triplet(tokens[mode].scrim)};`);
  for (const group of ["chart", "loader"]) {
    for (const [name, hex] of Object.entries(tokens[group][mode])) lines.push(`${indent}--sw-${group}-${name}: ${triplet(hex)};`);
  }
  return lines.join("\n");
}

export function generatePalette(tokens, version) {
  return `/* Space Works Design System ${version} (design-kit/tokens/tokens.json), generated by
 * scripts/sync-design-tokens.mjs. Do not edit by hand: run \`npm run tokens:sync\`.
 * Canonical sRGB triplets; sw- prefix avoids Tailwind utility-name collisions.
 * --sw-chart-* are the chart series (order: accent, info, success, warn, danger);
 * --sw-loader-* colour the box-open loader (app/styles/box-open.css).
 * The pinned source values are in tests/fixtures/design-tokens.json. */
:root {
${colourLines(tokens, "light", "  ")}
}

:root[data-color-mode="dark"],
.yy-dark-band {
${colourLines(tokens, "dark", "  ")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-color-mode]) {
${colourLines(tokens, "dark", "    ")}
  }
}
`;
}

export function generateMotion(tokens, version) {
  const { duration, easing, distance } = tokens.motion;
  const vars = (obj, prefix) => Object.entries(obj).map(([k, v]) => `--sw-${prefix}${k}: ${v};`);
  const set = (obj) => Object.entries(obj).map(([k, v]) => `--sw-${k}: ${v};`).join(" ");
  const zeroed = {
    ...Object.fromEntries(Object.keys(duration).map((k) => [`dur-${k}`, "0ms"])),
    ...tokens.motion["kiosk-tv"],
  };
  return `/* Space Works Design System ${version} motion tokens (design-kit/tokens/tokens.json),
 * generated by scripts/sync-design-tokens.mjs. Do not edit by hand.
 * Durations: fast = press/hover/exit, base = overlays and indicators, slow = route settle.
 * Curves: standard = most movement, enter = arrivals, exit = departures.
 * Distances are tokens so kiosk and TV screens zero them and keep only the fade. */
:root {
${[...vars(duration, "dur-"), ...vars(easing, "ease-"), ...vars(distance, "")].map((l) => `  ${l}`).join("\n")}
}
.sw-kiosk, .sw-tv { ${set(tokens.motion["kiosk-tv"])} }
@media (prefers-reduced-motion: reduce) {
  :root { ${set(zeroed)} }
}
`;
}

export function generateFixture(tokens) {
  const { brand, fonts, light, dark } = tokens;
  const chart = { light: tokens.chart.light, dark: tokens.chart.dark, order: tokens.chart.order };
  const loader = { light: tokens.loader.light, dark: tokens.loader.dark };
  return `${JSON.stringify({ brand, fonts, light, dark, chart, loader }, null, 2)}\n`;
}

const FONT_FILES = ["Gilroy-ExtraBold.woff2", "Gilroy-Light.woff2", "Outfit-Variable.woff2", "Unbounded-Variable.woff2"];

function syncFiles(kit) {
  const fonts = path.join(root, "public/brand/fonts");
  rmSync(path.join(fonts, "LICENSES"), { recursive: true, force: true });
  mkdirSync(path.join(fonts, "LICENSES"), { recursive: true });
  for (const file of FONT_FILES) cpSync(path.join(kit, "fonts", file), path.join(fonts, file));
  for (const file of readdirSync(path.join(kit, "fonts/LICENSES"))) {
    cpSync(path.join(kit, "fonts/LICENSES", file), path.join(fonts, "LICENSES", file));
  }
  mkdirSync(path.join(root, "public/brand/logo"), { recursive: true });
  for (const file of readdirSync(path.join(kit, "logo")).filter((f) => f.endsWith(".svg"))) {
    const target = path.join(root, "public/brand/logo", file);
    const source = readFileSync(path.join(kit, "logo", file));
    if (!existsSync(target) || !readFileSync(target).equals(source)) writeFileSync(target, source);
  }
}

function main() {
  const fromIndex = process.argv.indexOf("--from");
  const kit = path.resolve(fromIndex > -1 ? process.argv[fromIndex + 1] : path.join(root, "design-kit"));
  const tokensFile = path.join(kit, "tokens/tokens.json");
  if (!existsSync(tokensFile)) {
    console.error(`Design System not found at ${kit}. Run: git submodule update --init design-kit`);
    process.exit(1);
  }
  const tokens = JSON.parse(readFileSync(tokensFile, "utf8"));
  const version = kitVersion(readFileSync(path.join(kit, "README.md"), "utf8"));
  writeFileSync(path.join(root, "app/styles/palette.css"), generatePalette(tokens, version));
  writeFileSync(path.join(root, "app/styles/motion.css"), generateMotion(tokens, version));
  writeFileSync(path.join(root, "tests/fixtures/design-tokens.json"), generateFixture(tokens));
  const motion = (file) => readFileSync(path.join(kit, "motion", file), "utf8");
  writeFileSync(path.join(root, "app/styles/box-open.css"), generateBoxOpenCss(motion("box-open/box-open.css"), tokens, version));
  writeFileSync(path.join(root, "components/brand/boxOpenMarkup.ts"), generateBoxOpenMarkup(motion("box-open/box-open-markup.html"), tokens, version));
  writeFileSync(path.join(root, "app/styles/theme-reveal.css"), generateThemeRevealCss(motion("theme-reveal/theme-reveal.css"), version));
  syncFiles(kit);
  console.log(`Synced Design System ${version} from ${kit}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
